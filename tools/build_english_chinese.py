"""Generate data/english/english-chinese.tsv from the pinned CC-CEDICT and CC-Canto glosses.

The file maps an English word to Traditional headwords whose gloss is that
word, with the position of that gloss. Candidates are ranked at run time with
the installed dictionary's weights; headwords absent from it are not offered.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from cantonese_ime.english import MAX_TRANSLATIONS_PER_WORD, TRANSLATION_SOURCES, TRANSLATIONS, gloss_index


def render(sources=TRANSLATION_SOURCES) -> str:
    index: dict[str, dict[str, int]] = {}
    for source in sources:
        with source.open(encoding="utf-8") as stream:
            for word, headwords in gloss_index(stream).items():
                merged = index.setdefault(word, {})
                for headword, position in headwords.items():
                    merged[headword] = min(merged.get(headword, position), position)
    lines = ["# English word -> Traditional headword:gloss position. Generated by tools/build_english_chinese.py;",
             "# derived from CC-CEDICT and CC-Canto (CC BY-SA); see data/THIRD_PARTY_NOTICES.md."]
    for source in sources:
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        lines.append(f"# source {source.relative_to(PROJECT_ROOT).as_posix()} sha256 {digest}")
    for word in sorted(index):
        best = sorted(index[word].items(), key=lambda item: (item[1], item[0]))[:MAX_TRANSLATIONS_PER_WORD]
        lines.append(word + "\t" + " ".join(f"{headword}:{position}" for headword, position in best))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=TRANSLATIONS)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(render().encode("utf-8"))
    print(args.output)


if __name__ == "__main__":
    main()
